"""Generate tests/bg3/runes.toml: one case per Rune Shaper spell variant (free, slot, upcast), the container-test rule
(bg3_lint_container_tests: one case per behaviour group). Rerun after adding a rune or an upcast level:
    python tests/gen/gen_rune_cases.py"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "..", "Public", "BigbyPresents-Backgrounds-Feats_8829ee20-0f23-f443-627f-521db0ee8206",
                    "Stats", "Generated", "Data")
OUT = os.path.join(HERE, "..", "bg3", "runes.toml")

WOLF = '{ as = "A", template = "wolf", faction = "hostile", hp = 300, distance = %s }'
# rune -> (target, spawn distance or None, a failed save to force, what a cast must leave behind)
RUNES = {
    "ChromaticOrb": ("A", 6, None, []),
    "ComprehendLanguages": ("host", None, None, ['{ target = "host", status_applied = ["COMPREHEND_LANGUAGES"] }']),
    "ArmorOfAgathys": ("host", None, None, ['{ target = "host", status_applied_any = ["ARMOR_OF_AGATHYS"%s] }']),
    "DisguiseSelf": ("host", None, None, []),
    "SpeakWithAnimals": ("host", None, None, ['{ target = "host", status_applied = ["PETPAL"] }']),
    "Command": ("A", 3, "Wisdom", ['{ target = "A", status_applied = ["COMMAND_HALT"] }']),
    "Entangle": ("A", 4, "Strength", []),
    "FogCloud": ("A", 4, None, []),
    "Goodberry": ("host", None, None, []),
    "InflictWounds": ("A", 1.0, "Constitution", ['{ target = "A", damage_type = "Necrotic" }']),
    "Longstrider": ("host", None, None, ['{ target = "host", status_applied = ["LONGSTRIDER"] }']),
    "Sanctuary": ("host", None, None, ['{ target = "host", status_applied = ["SANCTUARY"] }']),
    "BurningHands": ("A", 2, "Dexterity", ['{ target = "A", damage_type = "Fire" }']),
    "Thunderwave": ("A", 2, "Constitution", ['{ target = "A", damage_type = "Thunder" }']),
}


# surfaces outlast a case (fog blinds, vines entangle) and spoiled the cases after them in one session: these run last
LAST = ("FogCloud", "Entangle")


def entries():
    names = []
    for f in sorted(os.listdir(DATA)):
        if f.endswith(".txt"):
            names += re.findall(r'^new entry "([^"]+)"', open(os.path.join(DATA, f), encoding="utf-8").read(), re.M)
    return sorted(names, key=lambda n: any(k in n for k in LAST))


def main():
    out = ["# GENERATED by tests/gen/gen_rune_cases.py - do not edit by hand.",
           "# One case per Rune Shaper spell variant: the free cast (its rune charge) and every spell-slot level.", "",
           "[suite]", 'name = "Rune Shaper spells"', 'mode = "script"', ""]
    for name in entries():
        m = re.match(r"(?:Target|Zone|Shout|Projectile)_PHB2024_(?:Rune_)?(\w+?)_(Free|Slot(?:_(\d))?)$", name)
        if not m or m.group(1) not in RUNES:
            continue
        rune, kind, lvl = m.group(1), m.group(2), int(m.group(3) or 1)
        target, dist, save, expect = RUNES[rune]
        expect = [e % (f', "ARMOR_OF_AGATHYS_{lvl}"' if kind != "Free" and lvl > 1 else "") if "%s" in e else e for e in expect]
        setup = []
        if kind != "Free":
            setup.append(f'{{ target = "host", boost = "ActionResource(SpellSlot,1,{lvl})" }}')
            # slot variants spent by the OnCast passive PHB2024_RuneSlotCost (the rune's unlock status grants it in play)
            if f"SpellId('{name}')" in open_all():
                setup.append('{ target = "host", passive = "PHB2024_RuneSlotCost" }')
                expect.append(f'{{ resource = "SpellSlot", level = {lvl}, amount_change = -1 }}')
        if save:
            setup.append(f'{{ target = "A", boost = "AbilityFailedSavingThrow({save})" }}')
        expect = expect or ["{ cast = true }"]
        title = f"Rune Shaper {rune}: {'free cast (rune charge)' if kind == 'Free' else f'cast with a level {lvl} slot'}"
        out += ["[[case]]", f'id = "rune-{name}"', 'build = "bigby-fighter"', f'title = "{title}"', f'spell = "{name}"',
                f'target = "{target}"']
        if save or rune == "InflictWounds":
            out.append("real_rolls = true")
        if dist:
            out.append(f"spawn = [{WOLF % dist}]")
        if setup:
            out.append(f"setup = [{', '.join(setup)}]")
        out += [f"expect = [{', '.join(expect)}]", ""]
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print(f"wrote {OUT}: {sum(1 for l in out if l == '[[case]]')} cases")


_ALL = None


def open_all():
    global _ALL
    if _ALL is None:
        _ALL = "".join(open(os.path.join(DATA, f), encoding="utf-8").read() for f in sorted(os.listdir(DATA)) if f.endswith(".txt"))
    return _ALL


if __name__ == "__main__":
    main()
